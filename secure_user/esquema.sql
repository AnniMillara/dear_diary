DROP DATABASE IF EXISTS esquema_diario;
CREATE DATABASE esquema_diario CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE esquema_diario;

CREATE TABLE usuarios (
 id_usuario INT PRIMARY KEY AUTO_INCREMENT,
 nombre VARCHAR(50) NOT NULL UNIQUE,
 contrasena VARCHAR(225) NOT NULL,
 created_at DATETIME DEFAULT CURRENT_TIMESTAMP,
 updated_at DATETIME DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
);

CREATE TABLE entradas (
 id_entrada INT PRIMARY KEY AUTO_INCREMENT,
 fecha DATE NOT NULL,
 contenido TEXT NOT NULL,
 usuario_id INT NOT NULL,
 created_at DATETIME DEFAULT CURRENT_TIMESTAMP,
 updated_at DATETIME DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 FOREIGN KEY (usuario_id) REFERENCES usuarios(id_usuario) ON DELETE CASCADE ON UPDATE CASCADE
);
